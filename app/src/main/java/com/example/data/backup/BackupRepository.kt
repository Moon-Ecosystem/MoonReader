/** A backup that can't be restored; [message] is shown to the user. */
class BackupException(message: String, cause: Throwable? = null) : Exception(message, cause)

/**
 * Backs up and restores everything the app stores about the library: reading progress, stats, collections,
 * favorites, AniList links, custom covers and settings. Comic files themselves are never included.
 *
 * Format (version 1), a ZIP holding:
 * - `manifest.json`: format name, version, creation time, app version and the library folder it was made from
 * - `library.json`: every database table as an array of rows
 * - `settings.json`: preferences as `{key: {type, value}}`
 * - `covers/<name>`: custom cover images, referenced from the manga rows' `coverPath`
 */
class BackupRepository(private val context: Context, private val dao: BackupDao) {

    /** Writes a backup of the current data to [out]; [libraryRoot] is the selected library folder. */
    suspend fun export(out: OutputStream, libraryRoot: String?) = withContext(Dispatchers.IO) {
        val data = dao.snapshot()
        val customDir = customCoversDir().absolutePath
        val covers = mutableMapOf<String, File>()
        // Only user-chosen covers are kept: folder and first-page covers are regenerated by the next scan
        val manga = data.manga.map { m ->
            val file = m.coverPath?.let(::File)?.takeIf { it.parent == customDir && it.isFile }
            m.copy(coverPath = file?.let { "$COVERS_DIR/${it.name}".also { path -> covers[path] = it } })
        }
        ZipOutputStream(out).use { zip ->
            fun write(name: String, json: Any) {
                zip.putNextEntry(ZipEntry(name))
                zip.write(json.toString().toByteArray())
                zip.closeEntry()
            }
            write(MANIFEST, JSONObject()
                .put("format", FORMAT)
                .put("version", VERSION)
                .put("createdAt", System.currentTimeMillis())
                .put("appVersion", BuildConfig.VERSION_NAME)
                .put("libraryRoot", libraryRoot))
            write(LIBRARY, libraryToJson(data.copy(manga = manga)))
            write(SETTINGS, settingsToJson())
            for ((path, file) in covers) {
                zip.putNextEntry(ZipEntry(path))
                file.inputStream().use { it.copyTo(zip) }
                zip.closeEntry()
            }
        }
    }

    /**
     * Replaces all library data with the backup in [input]. The whole backup is read and validated first, and
     * the tables are replaced in one transaction, so a bad backup changes nothing. IDs are rewritten from the
     * backup's library folder to [libraryRoot], the folder now selected.
     */
    suspend fun restore(input: InputStream, libraryRoot: String?) = withContext(Dispatchers.IO) {
        val files = readZip(input)
        val manifest = files[MANIFEST]?.let { parse { JSONObject(it.decodeToString()) } }
        if (manifest == null || manifest.optString("format") != FORMAT) throw BackupException("This isn't a Moon Reader backup")
        if (manifest.optInt("version") > VERSION) throw BackupException("This backup was made by a newer version of Moon Reader")
        val data = parse { libraryFromJson(JSONObject(files.getValue(LIBRARY).decodeToString())) }
        val settings = files[SETTINGS]?.let { parse { JSONObject(it.decodeToString()) } }

        val oldRoot = manifest.optString("libraryRoot")
        val id: (String) -> String =
            if (oldRoot.isNotEmpty() && libraryRoot != null) { s -> remapLibraryId(s, oldRoot, libraryRoot) } else { s -> s }

        // Cover files go first: if the database step fails they're only unused files, never a broken library
        val customDir = customCoversDir().apply { mkdirs() }
        val manga = data.manga.map { m ->
            val cover = m.coverPath?.let { path ->
                val name = path.substringAfterLast('/')
                val bytes = files[path]?.takeIf { path.startsWith("$COVERS_DIR/") && name.isNotEmpty() && name != ".." }
                bytes?.let { File(customDir, name).apply { writeBytes(it) }.absolutePath }
            }
            m.copy(
                id = id(m.id),
                folderUriString = id(m.folderUriString),
                lastReadChapterId = m.lastReadChapterId?.let(id),
                coverPath = cover
            )
        }
        dao.replaceAll(
            BackupData(
                manga = manga,
                chapterProgress = data.chapterProgress.map { it.copy(chapterId = id(it.chapterId), mangaId = id(it.mangaId)) },
                readingSessions = data.readingSessions.map { it.copy(chapterId = id(it.chapterId), mangaId = id(it.mangaId)) },
                collections = data.collections,
                collectionManga = data.collectionManga.map { it.copy(mangaId = id(it.mangaId)) },
                // Offline progress from the backup could overwrite newer AniList data; a refresh pulls the current state
                tracks = data.tracks.map { it.copy(mangaId = id(it.mangaId), pendingSync = false) },
                chapterOverrides = data.chapterOverrides.map { it.copy(chapterId = id(it.chapterId), mangaId = id(it.mangaId)) }
            )
        )
        settings?.let(::applySettings)
    }

    private fun customCoversDir() = File(context.filesDir, "custom_covers")

    private fun readZip(input: InputStream): Map<String, ByteArray> {
        val files = mutableMapOf<String, ByteArray>()
        var total = 0L
        try {
            ZipInputStream(input).use { zip ->
                while (true) {
                    val entry = zip.nextEntry ?: break
                    if (entry.isDirectory) continue
                    val bytes = zip.readBytes()
                    total += bytes.size
                    if (total > MAX_BACKUP_BYTES) throw BackupException("The backup is too large")
                    files[entry.name] = bytes
                }
            }
        } catch (e: java.util.zip.ZipException) {
            throw BackupException("The backup file is damaged", e)
        } catch (e: java.io.EOFException) { // a truncated file
            throw BackupException("The backup file is damaged", e)
        }
        return files
    }

    private fun <T> parse(block: () -> T): T = try {
        block()
    } catch (e: JSONException) {
        throw BackupException("The backup file is damaged", e)
    } catch (e: NoSuchElementException) {
        throw BackupException("The backup file is incomplete", e)
    }

    private fun settingsToJson(): JSONObject {
        val json = JSONObject()
        for ((key, value) in prefs().all) {
            if (key in PreferencesManager.BACKUP_EXCLUDED_KEYS) continue
            val type = when (value) {
                is Boolean -> "boolean"
                is Int -> "int"
                is Long -> "long"
                is Float -> "float"
                is String -> "string"
                else -> continue
            }
            json.put(key, JSONObject().put("type", type).put("value", value))
        }
        return json
    }

    private fun applySettings(json: JSONObject) {
        val editor = prefs().edit()
        for (key in json.keys()) {
            if (key in PreferencesManager.BACKUP_EXCLUDED_KEYS) continue
            val entry = json.optJSONObject(key) ?: continue
            when (entry.optString("type")) {
                "boolean" -> editor.putBoolean(key, entry.getBoolean("value"))
                "int" -> editor.putInt(key, entry.getInt("value"))
                "long" -> editor.putLong(key, entry.getLong("value"))
                "float" -> editor.putFloat(key, entry.getDouble("value").toFloat())
                "string" -> editor.putString(key, entry.getString("value"))
            }
        }
        editor.commit()
    }

    private fun prefs() = context.getSharedPreferences(PreferencesManager.PREFS_NAME, Context.MODE_PRIVATE)

    companion object {
        const val FORMAT = "moonreader-backup"
        const val VERSION = 1
        private const val MANIFEST = "manifest.json"
        private const val LIBRARY = "library.json"
        private const val SETTINGS = "settings.json"
        private const val COVERS_DIR = "covers"
        private const val MAX_BACKUP_BYTES = 512L * 1024 * 1024
    }
}

/**
 * Rewrites a series or chapter ID from the library folder [oldRoot] to [newRoot]. IDs are document URIs under
 * the folder's tree URI (or file paths under a plain folder), so the part after the folder stays the same when
 * the folder keeps its layout. IDs outside [oldRoot] are returned unchanged.
 */
internal fun remapLibraryId(id: String, oldRoot: String, newRoot: String): String {
    // A tree URI's documents are "<tree>/document/<tree document id>…", the id repeated encoded after /tree/
    fun base(root: String) = if (root.startsWith("content://")) "$root/document/${root.substringAfter("/tree/")}" else root
    val oldBase = base(oldRoot)
    if (oldRoot == newRoot || !id.startsWith(oldBase)) return id
    val rest = id.substring(oldBase.length)
    // Only whole path segments: "…/Manga2" must not match the folder "…/Manga"
    val isInside = rest.isEmpty() || rest == "_root" || rest.startsWith("%2F") || rest.startsWith("/")
    return if (isInside) base(newRoot) + rest else id
}

private fun JSONObject.stringOrNull(key: String): String? = if (isNull(key)) null else getString(key)

private inline fun <T> JSONArray.mapObjects(transform: (JSONObject) -> T): List<T> =
    List(length()) { transform(getJSONObject(it)) }

private fun libraryToJson(data: BackupData) = JSONObject()
    .put("manga", JSONArray(data.manga.map {
        JSONObject()
            .put("id", it.id)
            .put("title", it.title)
            .put("folderUriString", it.folderUriString)
            .put("coverPath", it.coverPath)
            .put("isFavorite", it.isFavorite)
            .put("lastReadChapterId", it.lastReadChapterId)
            .put("lastReadChapterTitle", it.lastReadChapterTitle)
            .put("lastReadPage", it.lastReadPage)
            .put("lastReadTime", it.lastReadTime)
            .put("totalChapters", it.totalChapters)
    }))
    .put("chapterProgress", JSONArray(data.chapterProgress.map {
        JSONObject()
            .put("chapterId", it.chapterId)
            .put("mangaId", it.mangaId)
            .put("chapterTitle", it.chapterTitle)
            .put("lastReadPage", it.lastReadPage)
            .put("totalPages", it.totalPages)
            .put("isRead", it.isRead)
            .put("isBookmarked", it.isBookmarked)
            .put("lastUpdatedTime", it.lastUpdatedTime)
    }))
    .put("readingSessions", JSONArray(data.readingSessions.map {
        JSONObject()
            .put("id", it.id)
            .put("mangaId", it.mangaId)
            .put("chapterId", it.chapterId)
            .put("chapterTitle", it.chapterTitle)
            .put("startedAt", it.startedAt)
            .put("endedAt", it.endedAt)
            .put("durationMillis", it.durationMillis)
            .put("startPage", it.startPage)
            .put("endPage", it.endPage)
            .put("pagesProgressed", it.pagesProgressed)
            .put("completedChapter", it.completedChapter)
    }))
    .put("collections", JSONArray(data.collections.map {
        JSONObject().put("id", it.id).put("name", it.name).put("position", it.position)
    }))
    .put("collectionManga", JSONArray(data.collectionManga.map {
        JSONObject().put("collectionId", it.collectionId).put("mangaId", it.mangaId)
    }))
    .put("tracks", JSONArray(data.tracks.map {
        JSONObject()
            .put("mangaId", it.mangaId)
            .put("remoteId", it.remoteId)
            .put("libraryId", it.libraryId)
            .put("title", it.title)
            .put("coverUrl", it.coverUrl)
            .put("status", it.status?.name)
            .put("progress", it.progress)
            .put("progressVolumes", it.progressVolumes)
            .put("totalChapters", it.totalChapters)
            .put("totalVolumes", it.totalVolumes)
            .put("score", it.score)
            .put("startedAt", it.startedAt)
            .put("completedAt", it.completedAt)
            .put("pendingSync", it.pendingSync)
    }))
    .put("chapterOverrides", JSONArray(data.chapterOverrides.map {
        JSONObject()
            .put("chapterId", it.chapterId)
            .put("mangaId", it.mangaId)
            .put("customTitle", it.customTitle)
            .put("isHidden", it.isHidden)
    }))

private fun libraryFromJson(json: JSONObject) = BackupData(
    manga = json.getJSONArray("manga").mapObjects {
        MangaEntity(
            id = it.getString("id"),
            title = it.getString("title"),
            folderUriString = it.getString("folderUriString"),
            coverPath = it.stringOrNull("coverPath"),
            isFavorite = it.optBoolean("isFavorite"),
            lastReadChapterId = it.stringOrNull("lastReadChapterId"),
            lastReadChapterTitle = it.stringOrNull("lastReadChapterTitle"),
            lastReadPage = it.optInt("lastReadPage"),
            lastReadTime = it.optLong("lastReadTime"),
            totalChapters = it.optInt("totalChapters")
        )
    },
    chapterProgress = json.getJSONArray("chapterProgress").mapObjects {
        ChapterProgressEntity(
            chapterId = it.getString("chapterId"),
            mangaId = it.getString("mangaId"),
            chapterTitle = it.getString("chapterTitle"),
            lastReadPage = it.optInt("lastReadPage"),
            totalPages = it.optInt("totalPages"),
            isRead = it.optBoolean("isRead"),
            isBookmarked = it.optBoolean("isBookmarked"),
            lastUpdatedTime = it.optLong("lastUpdatedTime")
        )
    },
    readingSessions = json.getJSONArray("readingSessions").mapObjects {
        ReadingSessionEntity(
            id = it.getLong("id"),
            mangaId = it.getString("mangaId"),
            chapterId = it.getString("chapterId"),
            chapterTitle = it.getString("chapterTitle"),
            startedAt = it.getLong("startedAt"),
            endedAt = it.getLong("endedAt"),
            durationMillis = it.getLong("durationMillis"),
            startPage = it.optInt("startPage"),
            endPage = it.optInt("endPage"),
            pagesProgressed = it.optInt("pagesProgressed"),
            completedChapter = it.optBoolean("completedChapter")
        )
    },
    collections = json.getJSONArray("collections").mapObjects {
        CollectionEntity(id = it.getLong("id"), name = it.getString("name"), position = it.optInt("position"))
    },
    collectionManga = json.getJSONArray("collectionManga").mapObjects {
        CollectionMangaEntity(collectionId = it.getLong("collectionId"), mangaId = it.getString("mangaId"))
    },
    tracks = json.getJSONArray("tracks").mapObjects {
        MangaTrackEntity(
            mangaId = it.getString("mangaId"),
            remoteId = it.getLong("remoteId"),
            libraryId = if (it.isNull("libraryId")) null else it.getLong("libraryId"),
            title = it.getString("title"),
            coverUrl = it.stringOrNull("coverUrl"),
            status = it.stringOrNull("status")?.let { s -> TrackStatus.entries.firstOrNull { e -> e.name == s } },
            progress = it.optInt("progress"),
            progressVolumes = it.optInt("progressVolumes"),
            totalChapters = it.optInt("totalChapters"),
            totalVolumes = it.optInt("totalVolumes"),
            score = it.optInt("score"),
            startedAt = it.stringOrNull("startedAt"),
            completedAt = it.stringOrNull("completedAt"),
            pendingSync = it.optBoolean("pendingSync")
        )
    },
    // Older backups have no chapter changes; an absent array reads as none
    chapterOverrides = json.optJSONArray("chapterOverrides")?.mapObjects {
        ChapterOverrideEntity(
            chapterId = it.getString("chapterId"),
            mangaId = it.getString("mangaId"),
            customTitle = it.stringOrNull("customTitle"),
            isHidden = it.optBoolean("isHidden")
        )
    }.orEmpty()
)
